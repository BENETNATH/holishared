def main():
    catalog = read_po(PO.open(encoding="utf-8"), locale="en")
    translated = 0
    missing = []
    for msg in catalog:
        if not msg.id:
            continue  # header
        if isinstance(msg.id, tuple):
            continue  # plural (none here)
        if msg.id in T:
            msg.string = T[msg.id]
            msg.flags.discard("fuzzy")
            translated += 1
        else:
            missing.append(msg.id)
    write_po(PO.open("wb"), catalog)
    print(f"Translated {translated} strings.")
    if missing:
        print(f"Untranslated ({len(missing)}):")
        for m in missing:
            print(f"  - {m}")


if __name__ == "__main__":
    main()
